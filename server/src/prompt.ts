function formatEntries(entries: EntryInput[]) {
  if (entries.length === 0) return '(записей за этот период нет)';
  return entries
    .map((e, i) => {
      const day = format(parseISO(e.createdAt), 'EEEE, d MMMM', { locale: ru });
      return `${i + 1}. [${day}] [${e.type} / ${e.emotion}] ${e.text}${e.tags.length ? ` (теги: ${e.tags.join(', ')})` : ''}`;
    })
    .join('\n');
}

function formatProfile(p: ProfileContext) {
  const parts: string[] = [];
  if (p.age !== undefined) parts.push(`возраст ${p.age}`);
  if (p.occupation) parts.push(`работа: ${p.occupation}`);
  if (p.habits) parts.push(`привычки: ${p.habits}`);
  return parts.length ? parts.join('; ') : 'нет данных';
}

interface TimelineItem {
  author: string;
  createdAt: string;
  entry: EntryInput;
}

function formatTimeline(req: GenerateReportRequest) {
  const timeline: TimelineItem[] = [
    ...req.entriesA.map((entry) => ({ author: req.userAName, createdAt: entry.createdAt, entry })),
    ...req.entriesB.map((entry) => ({ author: req.userBName, createdAt: entry.createdAt, entry })),
  ].sort((a, b) => new Date(a.createdAt).getTime() - new Date(b.createdAt).getTime());

  if (timeline.length === 0) return '(записей за этот период нет)';

  return timeline
    .map((item, i) => {
      const day = format(parseISO(item.createdAt), 'EEEE, d MMMM', { locale: ru });
      const e = item.entry;
      return `${i + 1}. [${day}] ${item.author}: [${e.type} / ${e.emotion}] ${e.text}${e.tags.length ? ` (теги: ${e.tags.join(', ')})` : ''}`;
    })
    .join('\n');
}

export function buildUserPrompt(req: GenerateReportRequest) {
  const previousBlock = req.previousNarrative
    ? `\nКраткий контекст предыдущего отчёта (для непрерывности, НЕ повторяй его дословно и не выдумывай продолжение, если новые записи этого не подтверждают):\n${req.previousNarrative}\n`
    : '';

  return `Период: ${req.weekLabel}

Партнёр A — ${req.userAName}. Профиль: ${formatProfile(req.profileA)}.
Партнёр B — ${req.userBName}. Профиль: ${formatProfile(req.profileB)}.
${previousBlock}
Хронология записей обоих партнёров за период (по датам):
${formatTimeline(req)}

Для справки — отдельно записи партнёра A (для plan A):
${formatEntries(req.entriesA)}

Отдельно записи партнёра B (для plan B):
${formatEntries(req.entriesB)}

Составь единую историю недели и индивидуальные планы для обоих партнёров согласно формату.`;
}

export const REPORT_JSON_SCHEMA = {
  name: 'weekly_report',
  strict: true,
  schema: {
    type: 'object',
    additionalProperties: false,
    properties: {
      narrative: { type: 'string' },
      narrativeDeep: { type: 'string' },
      planA: planSchema(),
      planB: planSchema(),
    },
    required: ['narrative', 'narrativeDeep', 'planA', 'planB'],
  },
} as const;

function planSchema() {
  return {
    type: 'array',
    minItems: 1,
    maxItems: 5,
    items: {
      type: 'object',
      additionalProperties: false,
      properties: {
        emoji: { type: 'string' },
        title: { type: 'string' },
      },
      required: ['emoji', 'title'],
    },
  };
}
